def sync_proxy_environment(proxy: str | None) -> None:
    """Spell the route out in `os.environ`: the proxy variables, or `NO_PROXY=*` for direct."""

    for name in PROXY_NAMES:
        if proxy:
            os.environ[name] = proxy
        else:
            os.environ.pop(name, None)
    no_proxy = LOCAL_HOSTS if proxy else "*"
    os.environ["NO_PROXY"] = no_proxy
    os.environ["no_proxy"] = no_proxy


def install_proxy_policy(proxy: Mapping[str, Any] | None) -> None:
    """FineSub's route discovery and API calls take the core's route, always (D17; plan 4.5 item 30).

    `proxy`: `{"policy": bool, "url": str | None}` -- whether the desktop's
    policy applies (it does not outside the desktop), and the route the core
    resolved for this process. Without the policy, or without a route, the
    route is direct: never the Windows system proxy, which only the core may
    turn into a setting. An explicit `[api] proxy` in FineSub's config still
    wins. A SOCKS route goes direct with a warning: the engine refuses SOCKS.
    """

    url = (proxy.get("url") or None) if proxy and proxy.get("policy") else None
    sync_proxy_environment(url)
    _pin_route_discovery(url)
    _pin_api_proxy(url)


def _pin_route_discovery(url: str | None) -> None:
    """`finesub_bootstrap.http_client`'s own route discovery answers the core's route.

    A package whose `finesub_bootstrap` has no route discovery (the
    correction and knowledge packages' compatibility packages) has nothing
    to pin here.
    """

    try:
        from finesub_bootstrap import http_client
    except ImportError:
        return
    discovered = getattr(http_client, "_environment_proxies", None)
    if discovered is None or getattr(discovered, _APP_POLICY_ATTRIBUTE, False):
        return

    def environment_proxies() -> list[str]:
        return []

    setattr(environment_proxies, _APP_POLICY_ATTRIBUTE, True)
    http_client._windows_proxy = lambda: url
    http_client._environment_proxies = environment_proxies


def _pin_api_proxy(url: str | None) -> None:
    """FineSub's API calls (`finesub.api_http`) take the core's route unless its config names one."""

    try:
        from finesub import api_http
    except Exception:  # noqa: BLE001 - the LLM layer is optional in some packages
        return
    original_configured = api_http.configured_proxy
    if getattr(original_configured, _APP_POLICY_ATTRIBUTE, False):
        return
    warned_socks = False

    def configured_proxy() -> str | None:
        nonlocal warned_socks
        explicit = original_configured()
        if explicit is not None:
            return explicit
        if url and url.lower().startswith("socks"):
            if not warned_socks:
                warned_socks = True
                print(
                    "Warning: the transcription engine does not support SOCKS proxies; "
                    "its API calls go direct. Use the proxy's HTTP port to route them.",
                    file=sys.stderr,
                )
            return api_http.DIRECT
        return url or api_http.DIRECT

    setattr(configured_proxy, _APP_POLICY_ATTRIBUTE, True)
    api_http.configured_proxy = configured_proxy


def install_region_policy() -> None:
    """Pin FineSub's region answer in this process to `global`, without asking the network.

    Every engine call site imports `resolve_region` from the module at call
    time, so replacing the module attribute reaches all of them. A package
    whose `finesub_bootstrap` has no `download_routes` has nothing to pin.
    """

    try:
        from finesub_bootstrap import download_routes
    except ImportError:
        return

    original = download_routes.resolve_region
    if getattr(original, _INSTALLED_ATTRIBUTE, False):
        return

    def resolve_region(data_root, *args: Any, **kwargs: Any):
        return download_routes.RouteDecision(region="global", source="ladder")

    setattr(resolve_region, _INSTALLED_ATTRIBUTE, True)
    resolve_region.__doc__ = original.__doc__
    download_routes.resolve_region = resolve_region


def install_gemini_overlay_policy() -> None:
    """Enable Nonoka-declared Gemini 4 catalog rows without modifying locked FineSub files.

    FineSub 0.7.0 only auto-wires unclaimed `local_agent` and custom HTTP rows
    from an override `model_catalog.toml`, and only emits `thinkingLevel` for
    `"gemini-3"` ids in `llm_runtime._thinking_config`. Both hooks are
    idempotent and leave all packaged rows and Gemini 2.5 / 3.x ids unchanged.
    """

    try:
        from finesub.llm.routing import model_catalog, model_routes
    except ImportError:
        model_catalog = None
        model_routes = None
    if model_catalog is not None and model_routes is not None:
        original_wire = model_routes._wire_unclaimed_catalog_target
        if not getattr(original_wire, _INSTALLED_ATTRIBUTE, False):
            def _wire_unclaimed_catalog_target(targets: Any, fact: Any) -> None:
                if (
                    fact.provider_kind == model_catalog.GEMINI_KIND
                    and fact.provider_tier in model_routes.BACKEND_PROVIDER_TIERS["gemini_rest"]
                ):
                    if fact.fact_id in targets:
                        raise model_routes.ModelRouteConfigError(
                            f"model_catalog {fact.fact_id!r}: its target would take the name of "
                            "a declared target; rename the model"
                        )
                    targets[fact.fact_id] = model_routes.ExecutionTarget(
                        id=fact.fact_id,
                        backend="gemini_rest",
                        fact_id=fact.fact_id,
                        enabled_by=fact.provider_tier,
                        native_search_tool=model_routes.target_search_tool(fact),
                    )
                    return
                original_wire(targets, fact)

            setattr(_wire_unclaimed_catalog_target, _INSTALLED_ATTRIBUTE, True)
            model_routes._wire_unclaimed_catalog_target = _wire_unclaimed_catalog_target

    try:
        from finesub.llm import llm_runtime
    except ImportError:
        return
    original_thinking = llm_runtime._thinking_config
    if getattr(original_thinking, _INSTALLED_ATTRIBUTE, False):
        return

    def _thinking_config(model_name: str, budget: Any, level: Any = None) -> Any:
        if "gemini-4" in (model_name or "").lower():
            return original_thinking("gemini-3", budget, level)
        return original_thinking(model_name, budget, level)

    setattr(_thinking_config, _INSTALLED_ATTRIBUTE, True)
    llm_runtime._thinking_config = _thinking_config


