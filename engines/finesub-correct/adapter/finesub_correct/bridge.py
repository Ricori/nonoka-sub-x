def install_llm_model_override(value: Any, task_groups: Mapping[str, Any] | None = None) -> None:
    """Apply a task's `llm_model` pin, or clear whatever a previous one left (moved from `nonoka_x.worker`).

    The engine's equivalent of `--llm-model`: a model group or route target
    that replaces the bound chain for one run, without touching the saved
    settings. Unconditional, because the overlay is process-global.

    A bare string pins every task group. A table may use either the desktop's
    route names (`{"correction": "..."}`, expanded through `task_groups`, the
    core's `TASK_GROUPS_BY_ROUTE`) or upstream's exact task groups.
    """

    try:
        from finesub.llm.routing.model_routes import install_runtime_preferred, parse_llm_model_args
    except ImportError:
        return
    if isinstance(value, Mapping):
        overlay = {str(key): str(item) for key, item in value.items()}
    elif isinstance(value, str) and value.strip():
        overlay = parse_llm_model_args([value.strip()])
    else:
        overlay = {}
    groups_by_route = {str(key): tuple(groups) for key, groups in (task_groups or {}).items()}
    expanded: dict[str, str] = {}
    for key, target in overlay.items():
        for group in groups_by_route.get(key, (key,)):
            previous = expanded.get(group)
            if previous is not None and previous != target:
                raise ValueError(
                    f"llm_model assigns conflicting targets to {group}: "
                    f"{previous!r} and {target!r}"
                )
            expanded[group] = target
    install_runtime_preferred(expanded)
