def _write_atomic(path: Path, text: str) -> None:
    partial = path.with_name(f".{path.name}.part")
    with open(partial, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    os.replace(partial, path)


_TOML_BARE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")


def _toml_key(key: str) -> str:
    return key if _TOML_BARE_KEY.fullmatch(key) else json.dumps(key, ensure_ascii=False)


def _toml_value(value: Any) -> str:
    """One TOML value: primitives, arrays, and inline tables."""

    if isinstance(value, Mapping):
        inner = ", ".join(f"{_toml_key(str(k))} = {_toml_value(v)}" for k, v in value.items())
        return "{" + inner + "}"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_toml_value(item) for item in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def derive_llm_files(run: Path, llm: Mapping[str, Any]) -> None:
    """Write `model_catalog.toml`, `finesub.toml` and, when needed, `.env` into `run`.

    `llm` (the launch context's): `endpoints` (`[{provider, model, row}]`, one
    per route over an HTTP transport, in catalog order), `routes`
    (`{route: {provider, model}}`, the `[nonoka_models]` table), `pins`
    (`[{group, provider, model, kind, tier, offered}]`, resolved here to
    catalog targets: `[llm.preferred_targets]`), `gemini_base_url` (only when
    changed). The texts are the ones the settings page wrote before WP-R5 (the
    quality gate's environment baseline compares them byte for byte).

    Reads FineSub's packaged route table and catalog to resolve the pins, so
    call it while the file variables name files that are not there yet.
    """

    install_gemini_overlay_policy()
    run.mkdir(parents=True, exist_ok=True)
    emitted: set[str] = set()
    tables = [CATALOG_HEADER]
    for endpoint in llm.get("endpoints") or ():
        explicit_target = str(endpoint.get("target") or "")
        if explicit_target:
            row = endpoint["row"]
            tier = str(row.get("provider_tier") or "")
            api_model_id = str(row.get("api_model_id") or "")
            if tier and api_model_id and (
                api_model_id in _packaged_local_agent_targets(tier)
                or api_model_id in _packaged_gemini_targets(tier)
            ):
                continue
            target = explicit_target
        else:
            target = custom_target(str(endpoint["provider"]), str(endpoint["model"]))
        emitted.add(target)
        tables.append(
            f"[models.{_toml_value(target)}]\n"
            + "".join(f"{key} = {_toml_value(value)}\n" for key, value in endpoint["row"].items())
        )
    _write_atomic(run / CATALOG_NAME, "\n".join(tables))

    routes = [
        (f"{route}_{field}", entry.get(field))
        for route, entry in (llm.get("routes") or {}).items()
        for field in ("provider", "model")
    ]
    preferred = [(pin["group"], _pin_target(pin, emitted)) for pin in llm.get("pins") or ()]
    blocks = [
        f"[{name}]\n" + "".join(f"{key} = {json.dumps(value)}\n" for key, value in entries)
        for name, entries in (
            ("nonoka_models", [(key, value) for key, value in routes if value]),
            ("llm.preferred_targets", [(key, value) for key, value in preferred if value]),
        )
        if entries
    ]
    config = run / CONFIG_NAME
    if blocks:
        _write_atomic(config, "\n".join(blocks))
    else:
        config.unlink(missing_ok=True)

    env_file = run / ENV_NAME
    gemini_base_url = str(llm.get("gemini_base_url") or "")
    if gemini_base_url:
        # The one setting the engine reads from its key file only
        # (`llm_runtime.gemini_base_url`); no key ever goes in it.
        _write_atomic(env_file, f"GEMINI_BASE_URL={gemini_base_url}\n")
    else:
        env_file.unlink(missing_ok=True)


def _pin_target(pin: Mapping[str, Any], emitted: set[str]) -> str | None:
    """The catalog target a route's pin names, or None to leave the group to the engine's own routing."""

    provider, model = str(pin.get("provider") or ""), str(pin.get("model") or "")
    if not provider or not model:
        return None
    kind = pin.get("kind")
    if kind == "gemini":
        packaged = _packaged_gemini_targets(str(pin["tier"])).get(model)
        if packaged is not None:
            return packaged
        overlay_target = str(pin.get("target") or "")
        return overlay_target if overlay_target and overlay_target in emitted else None
    if kind == "local_agent":
        offered = pin.get("offered")
        if offered is not None and model not in offered:
            return None
        packaged = _packaged_local_agent_targets(str(pin["tier"])).get(model)
        if packaged is not None:
            return packaged
        overlay_target = str(pin.get("target") or "")
        return overlay_target if overlay_target and overlay_target in emitted else None
    if kind == "http":
        # Only if its catalog row was written: a pin on a target the catalog
        # does not carry is worse than falling back.
        target = custom_target(provider, model)
        return target if target in emitted else None
    return None


def gemini_targets(tier: str) -> dict[str, str]:
    """`api_model_id -> fact id` of the packaged Gemini models of one key pool (`GEMINI_FREE`, `GEMINI_PAID`)."""

    from finesub.llm.routing.model_catalog import default_model_catalog

    return {
        entry.api_model_id: entry.fact_id
        for entry in default_model_catalog()
        if entry.provider_tier == tier and not entry.self_reported
    }


def _packaged_gemini_targets(tier: str) -> dict[str, str]:
    """`api_model_id -> fact id` of FineSub's packaged Gemini rows for `tier`.

    Reads only the packaged `model_catalog.toml` (ignoring any override file on
    disk), so repeated derivations into the same run directory stay deterministic.
    """

    from finesub.llm.routing.model_catalog import GEMINI_KIND, load_model_catalog

    return {
        entry.api_model_id: entry.fact_id
        for entry in load_model_catalog()
        if entry.provider_kind == GEMINI_KIND and entry.provider_tier == tier
    }


def _packaged_local_agent_targets(tier: str) -> dict[str, str]:
    """`api_model_id -> fact id` of FineSub's packaged local-agent rows for `tier`.

    Reads only the packaged `model_catalog.toml` (ignoring any override file on
    disk), so repeated derivations into the same run directory stay deterministic.
    """

    from finesub.llm.routing.model_catalog import LOCAL_AGENT_KIND, load_model_catalog

    return {
        entry.api_model_id: entry.fact_id
        for entry in load_model_catalog()
        if entry.provider_kind == LOCAL_AGENT_KIND and entry.provider_tier == tier
    }


def local_agent_targets(tier: str) -> list[tuple[Any, str]]:
    """(fact, target id) of every packaged local-agent model of `tier`, one per model, in roster order."""

    from finesub.llm.routing.model_routes import load_model_routes

    routes = load_model_routes(user_config={})
    by_model: dict[str, tuple[Any, str]] = {}
    for target in routes.targets.values():
        if target.backend != "local_agent":
            continue
        fact = routes.facts.get(target.fact_id)
        if fact is None or fact.provider_tier != tier:
            continue
        by_model[fact.api_model_id] = (fact, target.id)
    return list(by_model.values())


def forget_read_configuration() -> None:
    """Empty FineSub's per-process caches of its config, catalog and routes.

    Resolving the pins read FineSub's packaged defaults; the run must read the
    files just written, as a process that started with them would.
    """

    try:
        from finesub.config import clear_config_cache
        from finesub.llm.routing.model_catalog import default_model_catalog
        from finesub.llm.routing.model_routes import default_model_routes
    except ImportError:
        return
    clear_config_cache()
    default_model_catalog.cache_clear()
    default_model_routes.cache_clear()


def bind_llm_files(context: Mapping[str, Any]) -> dict[str, str]:
    """Name the three files in the run directory, derive them, and return the variables that name them."""

    run = Path((context.get("paths") or {})["run"])
    variables = file_variables(run)
    os.environ.update(variables)
    derive_llm_files(run, context.get("llm") or {})
    forget_read_configuration()
    return variables


