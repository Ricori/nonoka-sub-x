def classification_for(process: str) -> dict[str, tuple[str, str]]:
    """The package's half of the table for one process (`transcription`, ...): name -> (category, reason)."""

    return {name: (category, reason) for name, category, processes, reason in CLASSIFICATION if process in processes}


def drop_inherited() -> None:
    """Take every `FINESUB_*` variable out of this process's environment."""

    for name in list(os.environ):
        if name.upper().startswith(VARIABLE_PREFIX):
            del os.environ[name]


def bind_package_data(context: Mapping[str, Any]) -> None:
    """Hand a compatibility `finesub_bootstrap` the package's data directory (`paths.package_data`, D21).

    The correction and knowledge packages' `finesub_bootstrap` takes the
    locations the original derives from `%LOCALAPPDATA%\\FineSub` from here
    instead, so this runs before anything imports `finesub`. The original
    (the transcription package's) has nothing to bind: its default
    locations are the sandbox's (plan 4.5).
    """

    package_data = (context.get("paths") or {}).get("package_data")
    try:
        from finesub_bootstrap import _launch
    except ImportError:
        return
    if package_data:
        _launch.bind(package_data)


def custom_target(provider: str, model: str) -> str:
    """The catalog target id of a route over an HTTP transport: `nonoka-<provider>-<sha256[:12]>`."""

    digest = hashlib.sha256(f"{provider}\0{model}".encode("utf-8")).hexdigest()[:12]
    return f"nonoka-{provider}-{digest}"


def file_variables(run: Path) -> dict[str, str]:
    """The three files FineSub looks for, all in this process's run directory."""

    return {
        "FINESUB_CHECKOUT_DATA": "0",
        "FINESUB_CONFIG_FILE": str(run / CONFIG_NAME),
        "FINESUB_MODEL_CATALOG": str(run / CATALOG_NAME),
        "FINESUB_ENV_FILE": str(run / ENV_NAME),
        "FINESUB_ENV_PROTECT": "0",
    }


def secret_variables(context: Mapping[str, Any]) -> dict[str, str]:
    """The keys the core handed this package, as process variables (D3)."""

    return {str(name): str(value) for name, value in (context.get("secrets") or {}).items() if value}


def model_variables(context: Mapping[str, Any]) -> dict[str, str]:
    """The model layer and the caches the transcription half reads."""

    runtime = context.get("runtime") or {}
    models = Path(runtime["models"])
    variables = {
        "FINESUB_MODEL_DIR": str(models),
        "HF_HOME": str(models / HF_HOME_DIRECTORY),
        "TORCH_HOME": str(models / "torch"),
        **ACCELERATION_OFF,
        # The engine no longer downloads (WP-R7); a loader that would fetch a
        # missing file on its own fails instead of reaching the network.
        "HF_HUB_OFFLINE": "1",
    }
    cache = runtime.get("cache")
    if cache:
        # numba caches compiled functions beside their source unless told
        # otherwise, which is inside the read-only Python layer.
        variables["NUMBA_CACHE_DIR"] = str(Path(cache) / "numba")
    return variables


def knowledge_variables(context: Mapping[str, Any]) -> dict[str, str]:
    """The knowledge base this process reaches, and how it reaches the task's knowledge process."""

    variables: dict[str, str] = {}
    root = (context.get("paths") or {}).get("knowledge_root")
    if root:
        variables["FINESUB_KNOWLEDGE_ROOT"] = str(root)
    endpoint = context.get("knowledge_endpoint")
    if endpoint:
        variables[KNOWLEDGE_ENDPOINT_VARIABLE] = json.dumps(endpoint)
    return variables


# --- the files ----------------------------------------------------------------------------------------


def _write_atomic(path: Path, text: str) -> None:
    partial = path.with_name(f".{path.name}.part")
    with open(partial, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)
    os.replace(partial, path)


def _toml_value(value: Any) -> str:
    """One TOML value. JSON's string and array forms are valid TOML; a bool is `true` / `false` in both."""

    return json.dumps(value, ensure_ascii=False)


def derive_llm_files(run: Path, llm: Mapping[str, Any]) -> None:
    """Write `model_catalog.toml`, `finesub.toml` and, when needed, `.env` into `run`.

    `llm` (the launch context's): `endpoints` (`[{provider, model, row}]`, one
    per route over an HTTP transport, in catalog order), `routes`
    (`{route: {provider, model}}`, the `[nonoka_models]` table), `pins`
    (`[{group, provider, model, kind, tier, offered}]`, resolved here to
    catalog targets: `[llm.preferred_targets]`), `gemini_base_url` (only when
    changed). The texts are the ones the settings page wrote before WP-R5 (the
    quality gate's environment baseline compares them byte for byte).

    Reads FineSub's packaged route table and catalog to resolve the pins, so
    call it while the file variables name files that are not there yet.
    """

    run.mkdir(parents=True, exist_ok=True)
    emitted: set[str] = set()
    tables = [CATALOG_HEADER]
    for endpoint in llm.get("endpoints") or ():
        target = custom_target(str(endpoint["provider"]), str(endpoint["model"]))
        emitted.add(target)
        tables.append(
            f"[models.{_toml_value(target)}]\n"
            + "".join(f"{key} = {_toml_value(value)}\n" for key, value in endpoint["row"].items())
        )
    _write_atomic(run / CATALOG_NAME, "\n".join(tables))

    routes = [
        (f"{route}_{field}", entry.get(field))
        for route, entry in (llm.get("routes") or {}).items()
        for field in ("provider", "model")
    ]
    preferred = [(pin["group"], _pin_target(pin, emitted)) for pin in llm.get("pins") or ()]
    blocks = [
        f"[{name}]\n" + "".join(f"{key} = {json.dumps(value)}\n" for key, value in entries)
        for name, entries in (
            ("nonoka_models", [(key, value) for key, value in routes if value]),
            ("llm.preferred_targets", [(key, value) for key, value in preferred if value]),
        )
        if entries
    ]
    config = run / CONFIG_NAME
    if blocks:
        _write_atomic(config, "\n".join(blocks))
    else:
        config.unlink(missing_ok=True)

    env_file = run / ENV_NAME
    gemini_base_url = str(llm.get("gemini_base_url") or "")
    if gemini_base_url:
        # The one setting the engine reads from its key file only
        # (`llm_runtime.gemini_base_url`); no key ever goes in it.
        _write_atomic(env_file, f"GEMINI_BASE_URL={gemini_base_url}\n")
    else:
        env_file.unlink(missing_ok=True)


def _pin_target(pin: Mapping[str, Any], emitted: set[str]) -> str | None:
    """The catalog target a route's pin names, or None to leave the group to the engine's own routing."""

    provider, model = str(pin.get("provider") or ""), str(pin.get("model") or "")
    if not provider or not model:
        return None
    kind = pin.get("kind")
    if kind == "gemini":
        return gemini_targets(str(pin["tier"])).get(model)
    if kind == "local_agent":
        offered = pin.get("offered")
        if offered is not None and model not in offered:
            return None
        return {fact.api_model_id: target for fact, target in local_agent_targets(str(pin["tier"]))}.get(model)
    if kind == "http":
        # Only if its catalog row was written: a pin on a target the catalog
        # does not carry is worse than falling back.
        target = custom_target(provider, model)
        return target if target in emitted else None
    return None


def gemini_targets(tier: str) -> dict[str, str]:
    """`api_model_id -> fact id` of the packaged Gemini models of one key pool (`GEMINI_FREE`, `GEMINI_PAID`)."""

    from finesub.llm.routing.model_catalog import default_model_catalog

    return {
        entry.api_model_id: entry.fact_id
        for entry in default_model_catalog()
        if entry.provider_tier == tier and not entry.self_reported
    }


def local_agent_targets(tier: str) -> list[tuple[Any, str]]:
    """(fact, target id) of every packaged local-agent model of `tier`, one per model, in roster order."""

    from finesub.llm.routing.model_routes import load_model_routes

    routes = load_model_routes(user_config={})
    by_model: dict[str, tuple[Any, str]] = {}
    for target in routes.targets.values():
        if target.backend != "local_agent":
            continue
        fact = routes.facts.get(target.fact_id)
        if fact is None or fact.provider_tier != tier:
            continue
        by_model[fact.api_model_id] = (fact, target.id)
    return list(by_model.values())


def forget_read_configuration() -> None:
    """Empty FineSub's per-process caches of its config, catalog and routes.

    Resolving the pins read FineSub's packaged defaults; the run must read the
    files just written, as a process that started with them would.
    """

    try:
        from finesub.config import clear_config_cache
        from finesub.llm.routing.model_catalog import default_model_catalog
        from finesub.llm.routing.model_routes import default_model_routes
    except ImportError:
        return
    clear_config_cache()
    default_model_catalog.cache_clear()
    default_model_routes.cache_clear()


def bind_llm_files(context: Mapping[str, Any]) -> dict[str, str]:
    """Name the three files in the run directory, derive them, and return the variables that name them."""

    run = Path((context.get("paths") or {})["run"])
    variables = file_variables(run)
    os.environ.update(variables)
    derive_llm_files(run, context.get("llm") or {})
    forget_read_configuration()
    return variables


# --- the network ---------------------------------------------------------------------------------------


def sync_proxy_environment(proxy: str | None) -> None:
    """Spell the route out in `os.environ`: the proxy variables, or `NO_PROXY=*` for direct."""

    for name in PROXY_NAMES:
        if proxy:
            os.environ[name] = proxy
        else:
            os.environ.pop(name, None)
    no_proxy = LOCAL_HOSTS if proxy else "*"
    os.environ["NO_PROXY"] = no_proxy
    os.environ["no_proxy"] = no_proxy


def install_proxy_policy(proxy: Mapping[str, Any] | None) -> None:
    """FineSub's route discovery and API calls take the core's route, always (D17; plan 4.5 item 30).

    `proxy`: `{"policy": bool, "url": str | None}` -- whether the desktop's
    policy applies (it does not outside the desktop), and the route the core
    resolved for this process. Without the policy, or without a route, the
    route is direct: never the Windows system proxy, which only the core may
    turn into a setting. An explicit `[api] proxy` in FineSub's config still
    wins. A SOCKS route goes direct with a warning: the engine refuses SOCKS.
    """

    url = (proxy.get("url") or None) if proxy and proxy.get("policy") else None
    sync_proxy_environment(url)
    _pin_route_discovery(url)
    _pin_api_proxy(url)


def _pin_route_discovery(url: str | None) -> None:
    """`finesub_bootstrap.http_client`'s own route discovery answers the core's route.

    A package whose `finesub_bootstrap` has no route discovery (the
    correction and knowledge packages' compatibility packages) has nothing
    to pin here.
    """

    try:
        from finesub_bootstrap import http_client
    except ImportError:
        return
    discovered = getattr(http_client, "_environment_proxies", None)
    if discovered is None or getattr(discovered, _APP_POLICY_ATTRIBUTE, False):
        return

    def environment_proxies() -> list[str]:
        return []

    setattr(environment_proxies, _APP_POLICY_ATTRIBUTE, True)
    http_client._windows_proxy = lambda: url
    http_client._environment_proxies = environment_proxies


def _pin_api_proxy(url: str | None) -> None:
    """FineSub's API calls (`finesub.api_http`) take the core's route unless its config names one."""

    try:
        from finesub import api_http
    except Exception:  # noqa: BLE001 - the LLM layer is optional in some packages
        return
    original_configured = api_http.configured_proxy
    if getattr(original_configured, _APP_POLICY_ATTRIBUTE, False):
        return
    warned_socks = False

    def configured_proxy() -> str | None:
        nonlocal warned_socks
        explicit = original_configured()
        if explicit is not None:
            return explicit
        if url and url.lower().startswith("socks"):
            if not warned_socks:
                warned_socks = True
                print(
                    "Warning: the transcription engine does not support SOCKS proxies; "
                    "its API calls go direct. Use the proxy's HTTP port to route them.",
                    file=sys.stderr,
                )
            return api_http.DIRECT
        return url or api_http.DIRECT

    setattr(configured_proxy, _APP_POLICY_ATTRIBUTE, True)
    api_http.configured_proxy = configured_proxy


def install_region_policy() -> None:
    """Pin FineSub's region answer in this process to `global`, without asking the network.

    Every engine call site imports `resolve_region` from the module at call
    time, so replacing the module attribute reaches all of them. A package
    whose `finesub_bootstrap` has no `download_routes` has nothing to pin.
    """

    try:
        from finesub_bootstrap import download_routes
    except ImportError:
        return

    original = download_routes.resolve_region
    if getattr(original, _INSTALLED_ATTRIBUTE, False):
        return

    def resolve_region(data_root, *args: Any, **kwargs: Any):
        return download_routes.RouteDecision(region="global", source="ladder")

    setattr(resolve_region, _INSTALLED_ATTRIBUTE, True)
    resolve_region.__doc__ = original.__doc__
    download_routes.resolve_region = resolve_region


