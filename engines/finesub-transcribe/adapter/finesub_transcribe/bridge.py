"""What FineSub reads, derived in this package's process from its launch context (plan 4.3 items 22, 23).

Moved from the core (`nonoka_x.finesub_bridge`, WP-R5) into the packages
(WP-P1): every engine package carries its own copy of this module, word for
word (`tests/test_engine_packages.py` keeps them equal); what differs between
the packages -- which variables each derives -- is in each package's
`__main__`.

The core describes the process it starts in a neutral launch context (R0
document 1.15): its run directory and state file, the model layer, its keys by
name, the LLM routes and endpoints, the proxy. Here, before anything of
FineSub's is imported for the run, that becomes FineSub's own variables and
files:

- every `FINESUB_*` variable this process inherited is dropped first, so only
  what is derived here reaches the engine;
- the three files FineSub looks for are always named, in this process's run
  directory, whether or not they are written: an unset variable would send it
  to its default locations, a named file that is not there reads as "nothing
  configured";
- `finesub.toml` (`[nonoka_models]`, `[llm.preferred_targets]`),
  `model_catalog.toml`, and a `.env` only when the Gemini base URL was changed
  (D3, D20); no key is ever written, each is a process variable, and
  `FINESUB_ENV_PROTECT=0` keeps the engine from rewriting the files (D22).

Two patches keep FineSub's network use the app's: its region answer is pinned
to `global` without asking the network (the separator stage asks before it
checks its files), and its route discovery and its API calls take the route
the core resolved -- direct when there is none, never the system proxy (D17).

What a package's process has in its environment is classified twice over:
the neutral half (`nonoka_x.engine_host.CLASSIFICATION`), which the core
builds the process from, and this module's `CLASSIFICATION`, what the bridge
writes on top from the launch context (plan 4.5 item 27).
"""

